@family("an_proc_status", "Analysis", "Моделирование процессов", "mark", 2.2, -0.3)
def _(rng):
    ent, st, ev, extra, late = rng.choice(STATUS)
    p = _p(rng)
    trans = [f"{st[0]} → {st[1]}: {ev[0]}", f"{st[1]} → {st[2]}: {ev[1]}", f"{st[2]} → {st[3]}: {ev[2]}",
             f"{st[0]} → {st[4]}: {ev[3]}", f"{st[1]} → {st[4]}: {ev[4]}"]
    # каждый вариант нарушает своё правило из шапки: выход из финального статуса, статус вне модели, переход в отмену не из того статуса
    v = _variant(rng, 3)
    bad = [rng.choice([f"{st[3]} → {st[2]}: повторная обработка", f"{st[4]} → {st[1]}: повторная отправка"]),
           f"{st[1]} → {extra}: пауза по запросу партнёра", f"{st[2]} → {st[4]}: {late}"][v]
    trans.append(bad)
    rng.shuffle(trans)
    lines = [f"Статусная модель: {ent} (обмен с партнёром {p})", f"Статусы (других нет): {', '.join(st)}",
             f"Финальные статусы: {st[3]}, {st[4]} — из них переходов нет", f"В «{st[4]}» переходят только из «{st[0]}» и «{st[1]}»"] + trans
