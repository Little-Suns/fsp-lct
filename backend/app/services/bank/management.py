@family("pm_plan_gantt", "Management", "Планирование и сроки", "mark", 2.2, -0.3)
def _(rng):
    feat, plan = rng.choice(FEATURES), rng.choice(GANTT)
    v = _variant(rng, 3)  # 0 — старт раньше конца зависимости, 1 — окно в плане короче длительности, 2 — исполнитель в отпуске
    durs = rng.sample(range(2, 9), len(plan))
    who = rng.sample(PEOPLE, len(plan))
    bad, day0 = rng.randint(1, len(plan) - 1), rng.choice([1, 3, 6])
    start, end = [], []
    for i, (_name, deps) in enumerate(plan):
        s = max((end[d] for d in deps), default=day0 - 1) + 1
        if i == bad and v == 0:
            s -= rng.randint(1, min(3, durs[deps[0]]))  # стартует, пока зависимость ещё не закончена
        e = s + durs[i] - 1
        if i == bad and v == 1:
            e -= rng.randint(1, min(3, durs[i] - 1))  # в окне плана дней меньше, чем длится задача
        start.append(s)
        end.append(e)
    if v == 2:  # отпуск исполнителя задачи bad пересекает её окно
        off = who[bad]
        a = rng.randint(start[bad], end[bad])
        vac = (a, a + rng.randint(2, 4))
    else:  # отпуск есть и здесь, но после задач этого человека
        j = rng.randrange(len(plan))
        off, a = who[j], end[j] + rng.randint(1, 3)
        vac = (a, a + rng.randint(2, 4))
    letters = "ABCDEFG"
    lines = ["задача | дней | после | исполнитель | план, дни квартала"]
    for i, (name, deps) in enumerate(plan):
        after = ", ".join(letters[d] for d in deps) or "—"
        lines.append(f"{letters[i]}. {name} | {durs[i]} | {after} | {who[i]} | {start[i]}–{end[i]}")
    return {"scene_title": "План фичи", "story": f"Техлид прислал план фичи «{feat}» по рабочим дням квартала. В колонке «после» — задачи, которые должны "
            f"закончиться до старта. {off} в отпуске в дни {vac[0]}–{vac[1]}.",
            "prompt": "Нажмите на строку, из-за которой план в таком виде невыполним.", "panel": {"type": "code", "lang": "text", "lines": lines}, "key": bad + 2}


@family("pm_plan_slack", "Management", "Планирование и сроки", "choice", 2.3, 0.9)
def _(rng):
    feat = rng.choice(FEATURES)
    v = _variant(rng, 3)  # 0 — задержка вне критического пути, 1 — задержка на критическом пути, 2 — ускорение критической задачи
    while True:
        da, df, s = rng.randint(2, 4), rng.randint(2, 4), rng.randint(2, 4)
        crit = rng.randint(10, 13)
        split = [rng.randint(3, crit - 3), rng.randint(3, crit - s - 3)]
        back, front = (crit, crit - s) if rng.random() < 0.5 else (crit - s, crit)
        b1 = split[0] if back == crit else split[1]
        f1 = split[1] if back == crit else split[0]
        tasks = [("A", "Аналитика и требования", da, "—"), ("B", "Бэкенд: API", b1, "A"), ("C", "Дизайн экранов", f1, "A"),
                 ("D", "Бэкенд: интеграция с оплатой", back - b1, "B"), ("E", "Вёрстка экранов", front - f1, "C"), ("F", "Приёмочное тестирование", df, "D, E")]
        short, long = (["B", "D"], ["C", "E"]) if back < front else (["C", "E"], ["B", "D"])
        pick = rng.choice(short if v == 0 else long)
        x = next(t for t in tasks if t[0] == pick)
        if v == 0:
            n = rng.choice([s - 1, s + 1, s + 2]) if s > 2 else rng.choice([s + 1, s + 2])
            right, cand = max(0, n - s), [n, 0, s, n + s, max(0, n - s) + 1, max(0, n - s) + 2]
        elif v == 1:
            n = rng.randint(2, 4)
            right, cand = n, [max(0, n - s), 0, n + s, n - 1, n + 1]
        else:
            n = s + rng.randint(1, 2)
            if x[2] <= n:
                continue
            right, cand = s, [n, 0, n - s, s + 1, n + 1]  # выигрыш ограничен запасом параллельной ветки
        break
    lines = [f"{c}. {name} — {d} дн., после: {dep}" for c, name, d, dep in tasks]
    if v == 2:
        story = f"Фича «{feat}» запланирована к концу квартала. Задачу «{x[1]}» можно сделать на {n} раб. дн. быстрее, если добавить в неё второго разработчика."
