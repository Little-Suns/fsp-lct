def _lum(h: str) -> float:
    """Относительная яркость цвета #RRGGBB по WCAG 2.x."""
    c = [int(h[i:i + 2], 16) / 255 for i in (1, 3, 5)]
    r, g, b = (x / 12.92 if x <= 0.03928 else ((x + 0.055) / 1.055) ** 2.4 for x in c)
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def _ratio(fg: str, bg: str) -> float:
    a, b = sorted((_lum(fg), _lum(bg)), reverse=True)
    return (a + 0.05) / (b + 0.05)


def _gray(rng, lo: float, hi: float, bg: str = "#FFFFFF") -> tuple[str, str]:
    """Серый с контрастом к фону в [lo, hi) и подпись контраста «4,6:1» (диапазоны берутся с запасом от порогов — округление их не пересекает)."""
    h = rng.choice([f"#{v:02X}{v:02X}{v:02X}" for v in range(256) if lo <= _ratio(f"#{v:02X}{v:02X}{v:02X}", bg) < hi])
    return h, f"{_ratio(h, bg):.1f}".replace(".", ",") + ":1"


def _slots(rng, slots: list[tuple[str, str]], k: int, header: list[str], bad: int) -> tuple[list[str], int]:
    """k строк спецификации из пар (верно, с ошибкой) в исходном порядке; строка bad — с ошибкой и всегда среди выбранных.
    Возвращает строки и номер строки с ошибкой с 1."""
    pick = sorted(rng.sample([i for i in range(len(slots)) if i != bad], k - 1) + [bad])
    lines = header + [slots[i][1] if i == bad else slots[i][0] for i in pick]
    return lines, len(header) + pick.index(bad) + 1


