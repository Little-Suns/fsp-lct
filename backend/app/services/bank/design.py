@family("ux_ab_srm", "Design", "Метрики и эксперименты", "choice", 2.4, 2.3)
def _(rng):
    na = rng.randint(48000, 52000)
    nb = round(na * rng.uniform(0.92, 0.95))
    ca, d = rng.uniform(3.0, 3.6), rng.uniform(0.25, 0.4)
    oa, ob = round(na * ca / 100), round(nb * (ca + d) / 100)
    pa, pb = oa / na, ob / nb
    pp = (oa + ob) / (na + nb)
    pv = erfc(abs(pb - pa) / sqrt(pp * (1 - pp) * (1 / na + 1 / nb)) / sqrt(2))  # двусторонний z-тест двух долей
    pt = "p < 0,001" if pv < 0.001 else f"p = {pv:.3f}".replace(".", ",")
    what = rng.choice(["новая страница оплаты", "одностраничное оформление", "новый выбор доставки"])
    lines = [f"Эксперимент: {what}, сплит 50/50, {rng.choice([14, 28])} дней", "группа | пользователей | заказов | конверсия",
             f"A | {na} | {oa} | {100 * oa / na:.2f} %".replace(".", ","), f"B | {nb} | {ob} | {100 * ob / nb:.2f} %".replace(".", ","),
             f"Разница конверсии: +{100 * ob / nb - 100 * oa / na:.2f}".replace(".", ",") + f" п. п., {pt}"]
    opts, key = _choice(rng, f"Сплит нарушен: в B на {round(100 * (na - nb) / na)} % меньше людей — сначала найти, кого B теряет", [
        f"Выкатывать B: прирост конверсии значим, {pt}, тест шёл полный срок",
        "Случайно отбросить часть пользователей A, чтобы сравнять группы, и пересчитать",
        "Продлить тест на неделю: с ростом выборки размеры групп выровняются сами",
    ])
    return {"scene_title": "Итоги теста", "story": "Аналитик прислал итоги эксперимента и предлагает выкатывать B.",
            "prompt": "Что делать с результатом?", "panel": {"type": "code", "lang": "text", "lines": lines}, "options": opts, "key": key}


